// Project Modal Renderer & Shop Connector
window.openProjectDetail = function(projectId) {
  const project = (window.TIMBER_PROJECTS || []).find(p => p.id === projectId);
  if (!project) return;

  const modal = document.getElementById("project-modal");
  const body = document.getElementById("project-modal-body");
  if (!modal || !body) return;

  body.innerHTML = `
    <div class="project-detail-content">
      <div class="project-detail-header">
        <span class="badge-tag-amber">${project.typology}</span>
        <h2>${project.title}</h2>
        <p class="text-muted"><i class="fa-solid fa-location-dot text-amber"></i> ${project.location} &bull; Architect: <strong>${project.architect}</strong></p>
      </div>

      <div class="project-detail-visual-stage">
        <div class="project-luminaire-glow-sim"></div>
        <div class="project-metric-overlay-grid">
          ${Object.entries(project.metrics).map(([k, v]) => `
            <div class="proj-metric-box">
              <span class="metric-val text-amber">${v}</span>
              <span class="metric-key">${k}</span>
            </div>
          `).join("")}
        </div>
      </div>

      <div class="project-detail-body-grid">
        <div class="project-narrative-col">
          <h3>Architectural Specification</h3>
          <p class="leading-relaxed text-sm text-muted mb-4">${project.fullDesc || project.shortDesc}</p>
          
          <blockquote class="project-architect-quote">
            <i class="fa-solid fa-quote-left text-amber"></i>
            <p>"${project.quote}"</p>
            <cite>&mdash; ${project.architect}</cite>
          </blockquote>
        </div>

        <div class="project-shop-connection-col">
          <div class="project-shop-box">
            <div class="project-shop-header">
              <i class="fa-solid fa-bag-shopping text-amber"></i>
              <h4>SHOP THE LIGHTS USED IN THIS PROJECT</h4>
            </div>
            <p class="text-xs text-muted mb-3">Directly order or specify the exact profile systems configured for ${project.title}:</p>

            <div class="project-used-products-list">
              ${project.featuredSystems.map(sys => {
                const prod = (window.TIMBER_PRODUCTS || []).find(p => p.id === sys.productId);
                const price = prod ? TimberHelpers.formatINR(prod.price) : "₹1,850";
                return `
                  <div class="proj-prod-card">
                    <div class="proj-prod-info">
                      <strong class="text-white text-sm">${sys.name}</strong>
                      <span class="text-xs text-amber block">${sys.role}</span>
                      <span class="text-xs text-muted">From ${price} / Meter</span>
                    </div>
                    <div class="proj-prod-actions">
                      <button class="btn btn-secondary btn-sm" onclick="window.ProductDetailEngine.open('${sys.productId}'); document.getElementById('project-modal').classList.remove('active');">
                        Quick View
                      </button>
                      <button class="btn btn-primary btn-sm" onclick="window.CartEngine.addItem('${sys.productId}', '1m', 'neutral', 'black', 1); TimberHelpers.showToast('Added project luminaire to cart', 'success');">
                        <i class="fa-solid fa-plus"></i> Add
                      </button>
                    </div>
                  </div>
                `;
              }).join("")}
            </div>

            <div class="mt-4 pt-3 border-t border-white/10 text-center">
              <a href="#contact" class="btn btn-outline btn-sm w-full" onclick="document.getElementById('project-modal').classList.remove('active');">
                Request Similar Project Schedule / BoQ
              </a>
            </div>
          </div>
        </div>
      </div>
    </div>
  `;

  modal.classList.add("active");
  document.body.style.overflow = "hidden";
  TimberHelpers.playTactileSound("click");
};
